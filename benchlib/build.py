"""Render the model into build/ and report build status. The database rebuild is added in P2."""

from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path

from benchlib import diagram
from benchlib.config import Paths
from benchlib.dialects.base import Dialect
from benchlib.model import Model, ModelError, validate_model

NO_BUILD = "no build yet"


@dataclass
class RenderResult:
    ddl: Path
    diagram: Path


def schema_sql(model: Model, dialect: Dialect) -> str:
    """Schema-less DDL for the whole model: tables, then declared foreign keys, then comments."""
    parts = [
        f"-- Generated by ./bench model render from schema {model.schema}, model version {model.version}. Do not edit.\n"
        "-- Names are unqualified: run it with search_path set to the target schema."
    ]
    parts += [dialect.table_ddl(table, model.relations) for table in model.tables.values()]
    parts += [dialect.fk_ddl(relation) for relation in model.relations if relation.declared]
    parts += [sql for sql in (dialect.comment_sql(table) for table in model.tables.values()) if sql]
    return "\n\n".join(parts) + "\n"


def render(model: Model, paths: Paths, dialect: Dialect) -> RenderResult:
    """Validate, then write build/<model>.sql and build/<model>.svg."""
    errors = validate_model(model)
    if errors:
        raise ModelError("model is invalid", errors)
    paths.build.mkdir(parents=True, exist_ok=True)
    paths.ddl.write_text(schema_sql(model, dialect), encoding="utf-8")
    paths.diagram.write_bytes(diagram.render_svg(model))
    return RenderResult(ddl=paths.ddl, diagram=paths.diagram)


def build_status(paths: Paths) -> str:
    """Status line for the current files compared with the last build stamp."""
    if not paths.build_stamp.exists():
        return NO_BUILD
    raise NotImplementedError("comparing files with the build stamp is implemented in P2")
